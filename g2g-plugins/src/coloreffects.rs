//! Colour lookup-table effects (`coloreffects`). Maps each pixel of a packed
//! RGBA / BGRA frame through one of GStreamer's five preset 256-entry RGB
//! tables, preserving format and geometry. CPU-only `no_std` baseline.
//!
//! The `heat`, `sepia` and `xray` presets are luma-mapped: the pixel's BT.709
//! luma indexes the table and the entry's three components replace R, G and B,
//! so the output is a one-dimensional tone ramp. `xpro` and `yellowblue` map
//! each component through its own column of the table instead, which keeps the
//! image's own colour structure. `none` is a pass-through.
//!
//! The tables are GStreamer's, byte for byte, so the same preset produces the
//! same picture here.

use core::future::Future;
use core::pin::Pin;

use alloc::boxed::Box;
use alloc::vec;

use g2g_core::{
    AsyncElement, Caps, CapsConstraint, ConfigureOutcome, ElementMetadata, G2gError, OutputSink,
    PadTemplate, PadTemplates, PipelinePacket, PropError, PropKind, PropValue, PropertySpec,
    RawVideoFormat,
};

use crate::pixel::rgba_rb_offsets;
use crate::videofx::{self, FilterState, PixelFilter};

const FORMATS: [RawVideoFormat; 2] = [RawVideoFormat::Rgba8, RawVideoFormat::Bgra8];

/// One entry per 8-bit input level, three components each.
const LUT_ENTRIES: usize = 256;
const LUT_CHANNELS: usize = 3;
const LUT_BYTES: usize = LUT_ENTRIES * LUT_CHANNELS;

/// BT.709 luma weights in 8-bit fixed point (0.2126, 0.7152, 0.0722), the form
/// GStreamer indexes the luma-mapped tables with.
const LUMA_R: u32 = 54;
const LUMA_G: u32 = 183;
const LUMA_B: u32 = 19;
const LUMA_SHIFT: u32 = 8;

/// The colour tables, named as GStreamer's `preset` enum nicks.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ColorEffectsPreset {
    /// Pass-through.
    None,
    /// Fake heat camera toning.
    Heat,
    /// Sepia toning.
    Sepia,
    /// Invert and slightly shade to blue.
    XRay,
    /// Cross processing toning.
    XPro,
    /// Yellow foreground, blue background.
    YellowBlue,
}

impl ColorEffectsPreset {
    fn from_str(s: &str) -> Option<Self> {
        match s {
            "none" => Some(Self::None),
            "heat" => Some(Self::Heat),
            "sepia" => Some(Self::Sepia),
            "xray" => Some(Self::XRay),
            "xpro" => Some(Self::XPro),
            "yellowblue" => Some(Self::YellowBlue),
            _ => None,
        }
    }

    fn as_str(self) -> &'static str {
        match self {
            Self::None => "none",
            Self::Heat => "heat",
            Self::Sepia => "sepia",
            Self::XRay => "xray",
            Self::XPro => "xpro",
            Self::YellowBlue => "yellowblue",
        }
    }

    /// The preset's colour table, or `None` for the pass-through preset.
    pub fn table(self) -> Option<&'static [u8; LUT_BYTES]> {
        match self {
            Self::None => None,
            Self::Heat => Some(HEAT_LUT),
            Self::Sepia => Some(SEPIA_LUT),
            Self::XRay => Some(XRAY_LUT),
            Self::XPro => Some(XPRO_LUT),
            Self::YellowBlue => Some(YELLOWBLUE_LUT),
        }
    }

    /// Whether the pixel's luma indexes the table (the entry then supplies all
    /// three output components) rather than each component indexing its own
    /// column.
    pub fn maps_luma(self) -> bool {
        matches!(self, Self::Heat | Self::Sepia | Self::XRay)
    }
}

/// # Example
///
/// ```no_run
/// use g2g_plugins::coloreffects::{ColorEffects, ColorEffectsPreset};
///
/// // coloreffects preset=sepia
/// let effect = ColorEffects::new().with_preset(ColorEffectsPreset::Sepia);
/// assert!(effect.preset().maps_luma());
/// ```
#[derive(Debug)]
pub struct ColorEffects {
    preset: ColorEffectsPreset,
    state: FilterState,
}

impl Default for ColorEffects {
    fn default() -> Self {
        Self::new()
    }
}

impl ColorEffects {
    /// A pass-through element; pick a table with [`with_preset`](Self::with_preset).
    pub fn new() -> Self {
        Self {
            preset: ColorEffectsPreset::None,
            state: FilterState::new(),
        }
    }

    pub fn with_preset(mut self, preset: ColorEffectsPreset) -> Self {
        self.preset = preset;
        self
    }

    pub fn preset(&self) -> ColorEffectsPreset {
        self.preset
    }
}

impl PixelFilter for ColorEffects {
    const FORMATS: &'static [RawVideoFormat] = &FORMATS;

    fn state(&self) -> &FilterState {
        &self.state
    }

    fn state_mut(&mut self) -> &mut FilterState {
        &mut self.state
    }

    fn apply(&mut self, format: RawVideoFormat, w: u32, h: u32, src: &[u8]) -> Box<[u8]> {
        let bytes = (w as usize) * (h as usize) * 4;
        let mut dst = vec![0u8; bytes].into_boxed_slice();
        dst.copy_from_slice(&src[..bytes]);
        if let Some(table) = self.preset.table() {
            map_pixels(format, &mut dst, table, self.preset.maps_luma());
        }
        dst
    }
}

/// Replace every pixel's colour with its table entry, in place.
fn map_pixels(format: RawVideoFormat, pixels: &mut [u8], table: &[u8; LUT_BYTES], by_luma: bool) {
    let (r_idx, b_idx) = rgba_rb_offsets(format);
    for px in pixels.as_chunks_mut::<4>().0 {
        let (r, g, b) = (px[r_idx] as u32, px[1] as u32, px[b_idx] as u32);
        let (mapped_r, mapped_g, mapped_b) = if by_luma {
            let luma = (r * LUMA_R + g * LUMA_G + b * LUMA_B) >> LUMA_SHIFT;
            let entry = luma as usize * LUT_CHANNELS;
            (table[entry], table[entry + 1], table[entry + 2])
        } else {
            (
                table[r as usize * LUT_CHANNELS],
                table[g as usize * LUT_CHANNELS + 1],
                table[b as usize * LUT_CHANNELS + 2],
            )
        };
        px[r_idx] = mapped_r;
        px[1] = mapped_g;
        px[b_idx] = mapped_b;
    }
}

impl AsyncElement for ColorEffects {
    type ProcessFuture<'a>
        = Pin<Box<dyn Future<Output = Result<(), G2gError>> + 'a>>
    where
        Self: 'a;

    fn metadata(&self) -> ElementMetadata {
        ElementMetadata::new(
            "Color Look-up Table filter",
            "Filter/Effect/Video",
            "Maps colours of the video input through a preset lookup table",
            "g2g",
        )
    }

    /// Reads host memory, so it takes system frames only. The allocation
    /// cascade turns that into a download demand on a GPU producer.
    fn input_domains(&self) -> g2g_core::memory::DomainSet {
        g2g_core::memory::DomainSet::only(g2g_core::memory::MemoryDomainKind::System)
    }

    fn intercept_caps(&self, upstream_caps: &Caps) -> Result<Caps, G2gError> {
        videofx::intercept_caps::<Self>(upstream_caps)
    }

    fn caps_constraint_as_transform(&self) -> CapsConstraint<'_> {
        videofx::same_caps_constraint::<Self>()
    }

    fn configure_pipeline(&mut self, absolute_caps: &Caps) -> Result<ConfigureOutcome, G2gError> {
        videofx::configure(self, absolute_caps)
    }

    fn process<'a>(
        &'a mut self,
        packet: PipelinePacket,
        out: &'a mut dyn OutputSink,
    ) -> Self::ProcessFuture<'a> {
        videofx::drive(self, packet, out)
    }

    fn properties(&self) -> &'static [PropertySpec] {
        COLOREFFECTS_PROPS
    }

    fn set_property(&mut self, name: &str, value: PropValue) -> Result<(), PropError> {
        match name {
            "preset" => {
                let s = value.as_str().ok_or(PropError::Type)?;
                self.preset = ColorEffectsPreset::from_str(s).ok_or(PropError::Value)?;
                Ok(())
            }
            _ => Err(PropError::Unknown),
        }
    }

    fn get_property(&self, name: &str) -> Option<PropValue> {
        match name {
            "preset" => Some(PropValue::Str(self.preset.as_str().into())),
            _ => None,
        }
    }
}

/// `ColorEffects`'s settable properties, named as GStreamer's (M1084).
static COLOREFFECTS_PROPS: &[PropertySpec] =
    &[
        PropertySpec::new("preset", PropKind::Str, "colour effect preset to use")
            .with_enum_values("none | heat | sepia | xray | xpro | yellowblue")
            .with_default("none"),
    ];

impl PadTemplates for ColorEffects {
    fn pad_templates() -> alloc::vec::Vec<PadTemplate> {
        videofx::pad_templates::<Self>()
    }
}

